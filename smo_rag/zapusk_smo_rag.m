%  Как запустить:
%    1) Откройте этот файл в MATLAB (Open).
%    2) Нажмите Run (зелёная кнопка)  ИЛИ  в Command Window наберите:
%           zapusk_smo_rag
%    3) Появятся графики и цифры в Command Window (на русском).
%
%  Цель модели - загрузка сервера S (RAG + Ollama / GPU).
%  Графики интервала и времени обслуживания - ТЕСТ настройки, не вывод.

clear; clc; close all;
rng(7);

fprintf('\n========== СМО RAG-сервера ПсковГУ ==========\n');
fprintf('A - источник запросов (студенты, преподаватели, гости)\n');
fprintf('Q - очередь FastAPI (FIFO)\n');
fprintf('S - сервер (обслуживающий прибор, как касса)\n');
fprintf('R - выход: ответ с источниками\n\n');

%% ---------- 1. ТЕСТИРУЮЩИЙ ПРОГОН (проверка настроек) ----------
% Заявка раз в 10 с, обработка ~2 с, горизонт 200 с.
% Это НЕ цель работы, а проверка: правильно ли собрана модель.

T_test   = 200;     % с
dtA_test = 10;      % с, период поступления
svcMin   = 1.5;     % с
svcMax   = 2.5;     % с

[arr, svc, waitV, tOsi, u_cum, rho, n] = smo_progon( ...
    T_test, dtA_test, 'const', svcMin, svcMax, 'uniform', 7);

fprintf('--- ТЕСТ НАСТРОЙКИ ---\n');
fprintf('Заявок: %d за %.0f с\n', n, T_test);
fprintf('Средний интервал поступления: %.2f с  (должно быть 10)\n', mean(diff(arr)));
fprintf('Среднее время обслуживания:   %.2f с  (должно быть ~2)\n', mean(svc));
fprintf('Загрузка сервера rho:         %.2f  (ожидаем ~0.20 = 2/10)\n', rho);
fprintf('Среднее ожидание в очереди:   %.2f с\n\n', mean(waitV));

figure('Name','Тест настройки','Color','w');

subplot(3,1,1);
stairs(arr, dtA_test*ones(size(arr)), 'b','LineWidth',1.5); hold on;
plot(arr, dtA_test*ones(size(arr)), 'b.');
ylim([0 16]);
grid on;
xlabel('Модельное время, с');
ylabel('Интервал, с');
title('ТЕСТ: период поступления заявок (настройка, не цель)');

subplot(3,1,2);
stairs(arr, svc, 'Color',[0 0.5 0],'LineWidth',1.4); hold on;
plot(arr, svc, '.','Color',[0 0.5 0]);
plot([0 T_test],[2 2],'r--');
ylim([0 5]);
grid on;
xlabel('Модельное время, с');
ylabel('Обслуживание, с');
title('ТЕСТ: трудоёмкость обработки заявки (настройка, не цель)');

subplot(3,1,3);
plot(tOsi, u_cum, 'Color',[0.4 0 0.6],'LineWidth',1.8); hold on;
plot([0 T_test],[rho rho],'r--');
ylim([0 1.05]);
grid on;
xlabel('Модельное время, с');
ylabel('Загрузка rho');
title('ЦЕЛЬ: загрузка сервера S (тестовый прогон, rho ~ 0.20)');

%% ---------- 2. ЭКСПЕРИМЕНТ: рабочий день, разная трудоёмкость ----------
% 1 ед. времени = 1 с реального времени.
% Рабочий день университета / сайта ПсковГУ: 8 ч = 28800 с.
% Поток вопросов в пике: в среднем каждые 30 с (экспоненциальный).

T_day = 8*3600;          % 28800 с
dtA   = 30;              % средний интервал поступления, с
svc_set = [40 25 18 12 8];  % средние трудоёмкости, с
imena = { ...
    'тяжёлый (LLM+live-fetch)' , ...
    'текущий RAG+LLM'          , ...
    'целевой'                  , ...
    'ускоренная генерация'     , ...
    'только retrieval'         };

nExp = numel(svc_set);
rhoE = zeros(1,nExp);
waitE = zeros(1,nExp);
nE   = zeros(1,nExp);
svcE = zeros(1,nExp);

fprintf('--- ЭКСПЕРИМЕНТ, рабочий день 8 ч, поток каждые 30 с ---\n');
for k = 1:nExp
    [arrE, svcV, waitVk, tOsiE, uE, rhoE(k), nE(k)] = smo_progon( ...
        T_day, dtA, 'exp', svc_set(k), svc_set(k), 'exp', 20+k);
    waitE(k) = mean(waitVk);
    svcE(k)  = mean(svcV);
    fprintf(['%d) %5.0f с  | заявок %4d | факт.обсл. %5.1f с | ' ...
             'загрузка %5.1f %% | ожидание %7.1f с | %s\n'], ...
        k, svc_set(k), nE(k), svcE(k), 100*rhoE(k), waitE(k), imena{k});
end

% Главный график - загрузка за день при текущей трудоёмкости 25 с
[~,~,~,g25,u25,rho25,~] = smo_progon(T_day, dtA, 'exp', 25, 25, 'exp', 22);

figure('Name','Загрузка за рабочий день','Color','w');
plot(g25/3600, u25, 'Color',[0.4 0 0.6],'LineWidth',2); hold on;
plot([0 8],[0.60 0.60],'g--','LineWidth',1.4);
plot([0 8],[rho25 rho25],'r:','LineWidth',1.4);
xlim([0 8]); ylim([0 1.05]);
grid on;
xlabel('Время рабочего дня, ч');
ylabel('Загрузка сервера rho');
title('ЦЕЛЬ: загрузка сервера RAG за рабочий день (трудоёмкость 25 с)');
legend('накопленная загрузка','целевые 60 %', ...
       sprintf('итог %.0f %%',100*rho25),'Location','SouthEast');

figure('Name','Эксперимент трудоёмкость','Color','w');
bar(svc_set, 100*rhoE, 0.65); hold on;
plot([6 42],[60 60],'g--','LineWidth',1.5);
xlabel('Средняя трудоёмкость обработки заявки, с');
ylabel('Загрузка сервера, %');
title('Эксперимент: как трудоёмкость заявки меняет загрузку сервера S');
grid on;
ylim([0 120]);
legend('загрузка','целевые 60 %','Location','NorthEast');

figure('Name','Очередь','Color','w');
plot(svc_set, waitE, '-ob','LineWidth',1.8,'MarkerSize',8);
xlabel('Средняя трудоёмкость обработки, с');
ylabel('Среднее ожидание в очереди, с');
title('Сопутствующий эффект: очередь при росте трудоёмкости');
grid on;

fprintf('\nРекомендация: держать среднюю обработку около 18 с,');
fprintf(' тогда загрузка сервера близка к 60 %% и очередь не разгоняется.\n');
fprintf('============================================\n');
